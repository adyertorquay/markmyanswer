export function getPracticeQuestion(id: string): PracticeQuestion | undefined {
  return PRACTICE_QUESTIONS.find((q) => q.id === id);
}

// The browser sends the question text, not an id, so match on that.
export function findMarkScheme(question: string, type: QuestionType, marks: number): string | undefined {
  const text = question.trim();
  return PRACTICE_QUESTIONS.find((q) => q.question === text && q.type === type && q.marks === marks)?.markScheme;
}
